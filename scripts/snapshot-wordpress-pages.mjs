import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parse, serializeOuter } from 'parse5';

const origin = 'https://eudiasporacouncil.org';
const routes = [
  '/',
  '/entry/',
  '/status/',
  '/contact/',
  '/fee/',
  '/privacy/',
  '/agreement/',
  '/service/',
  '/mentions-legales/',
  '/sitemap/',
  '/page_cat/uketa/',
  '/page_cat/site/',
];

const walk = (node, visit) => {
  visit(node);
  for (const child of node.childNodes ?? []) walk(child, visit);
  if (node.content) walk(node.content, visit);
};

const findFirst = (root, predicate) => {
  let result;
  walk(root, (node) => {
    if (!result && predicate(node)) result = node;
  });
  return result;
};

const attr = (node, name) => node?.attrs?.find((item) => item.name === name)?.value;

const textContent = (node) => {
  if (!node) return '';
  if (node.nodeName === '#text') return node.value;
  return (node.childNodes ?? []).map(textContent).join('');
};

const hasClass = (node, className) =>
  (attr(node, 'class') ?? '').split(/\s+/).includes(className);

const assetUrls = new Set();
const snapshots = {};

for (const route of routes) {
  const response = await fetch(new URL(route, origin));
  if (!response.ok) throw new Error(`${response.status} ${route}`);

  const document = parse(await response.text());
  const bodyNode = findFirst(document, (node) => node.tagName === 'body');
  const titleNode = findFirst(document, (node) => node.tagName === 'title');
  const descriptionNode = findFirst(
    document,
    (node) => node.tagName === 'meta' && attr(node, 'name') === 'description',
  );
  const headerDescriptionNode = findFirst(document, (node) => hasClass(node, 'header-description'));
  const headerNode = findFirst(document, (node) => node.tagName === 'header');
  const desktopNavNode = findFirst(
    document,
    (node) => node.tagName === 'nav' && hasClass(node, 'global-nav') && hasClass(node, 'pc-only'),
  );
  const mobileNavNode = findFirst(document, (node) => attr(node, 'id') === 'global-nav-sp');
  const mainNode = findFirst(document, (node) => node.tagName === 'main');
  const footerNode = findFirst(document, (node) => node.tagName === 'footer');
  const footerFixedNode = findFirst(document, (node) => hasClass(node, 'footer-fixed'));

  if (!headerNode || !desktopNavNode || !mobileNavNode || !mainNode || !footerNode) {
    throw new Error(`Missing page chrome on ${route}`);
  }

  for (const root of [headerNode, desktopNavNode, mobileNavNode, mainNode, footerNode, footerFixedNode]) {
    if (!root) continue;
    walk(root, (node) => {
      for (const name of ['src', 'srcset']) {
        const value = attr(node, name);
        if (!value) continue;
        for (const candidate of value.split(',')) {
          const rawUrl = candidate.trim().split(/\s+/)[0];
          const url = new URL(rawUrl, origin);
          if (url.origin === origin && url.pathname.startsWith('/wp-content/')) {
            assetUrls.add(url.href);
          }
        }
      }
    });
  }

  snapshots[route] = {
    title: textContent(titleNode).trim(),
    description: attr(descriptionNode, 'content') ?? '',
    headerDescription: textContent(headerDescriptionNode).replace(/\s+/g, ' ').trim(),
    topPage: route === '/',
    bodyClass: (attr(bodyNode, 'class') ?? '').replace(/\s+/g, ' ').trim(),
    headerHtml: serializeOuter(headerNode),
    desktopNavHtml: serializeOuter(desktopNavNode),
    mobileNavHtml: serializeOuter(mobileNavNode),
    mainHtml: serializeOuter(mainNode),
    footerHtml: serializeOuter(footerNode),
    footerFixedHtml: footerFixedNode ? serializeOuter(footerFixedNode) : '',
  };
}

for (const href of [...assetUrls].sort()) {
  const url = new URL(href);
  const response = await fetch(url);
  if (!response.ok) {
    console.warn(`Skipped unavailable source asset: ${response.status} ${href}`);
    continue;
  }
  const target = path.join('public', url.pathname);
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, Buffer.from(await response.arrayBuffer()));
}

for (const stylesheet of ['style.css', 'top.css', 'page.css']) {
  const url = new URL(`/wp-content/themes/uketa-fr/assets/css/${stylesheet}`, origin);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  await writeFile(path.join('public/assets/css', stylesheet), Buffer.from(await response.arrayBuffer()));
}

const output = `// Generated by scripts/snapshot-wordpress-pages.mjs.\n` +
  `// WordPress is the content source of truth for these existing routes.\n` +
  `export const wordpressSnapshots = ${JSON.stringify(snapshots, null, 2)} as const;\n`;

await mkdir('src/content', { recursive: true });
await writeFile('src/content/wordpress-snapshots.ts', output, 'utf8');

console.log(`Snapshotted ${routes.length} routes and ${assetUrls.size} content assets.`);
